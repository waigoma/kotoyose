"""Antigravity CLI 向けの一時 workspace customization overlay。

Kotoyose の provider 非依存設定 (MCP / Skills / Agents) を Antigravity が workspace
から自動 discovery できる plugin 形式へ変換する。Google AI Pro / Ultra の
subscription-backed CLI 認証をそのまま使うため、ユーザーの global Antigravity
設定は変更しない。
"""

from __future__ import annotations

import json
import re
import shutil
import threading
import uuid
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from ..logging_setup import log
from .translation import TranslatedRuntimeConfig

_PLUGIN_PARENT = Path(".agents/plugins")
_PLUGIN_PREFIX = ".kotoyose-runtime-"
_MARKER = ".kotoyose-generated.json"
_GIT_EXCLUDE_RULE = "/.agents/plugins/.kotoyose-runtime-*"
_SAFE_NAME = re.compile(r"[^A-Za-z0-9_-]+")
_LEASE_LOCK = threading.Lock()
_LEASED_WORKSPACES: set[Path] = set()

# Kotoyose / Claude の built-in tool 名から Antigravity custom-agent tool 名への
# conservative mapping。未知の tool は勝手に広い権限へ変換せず drop する。
_TOOL_MAP = {
    "Read": "view_file",
    "Glob": "find_file",
    "Grep": "grep_search",
    "Bash": "run_command",
    "Write": "write_to_file",
    "Edit": "replace_file_content",
    "WebSearch": "search_web",
    "WebFetch": "read_url_content",
}
_MODEL_MAP = {
    "inherit": "inherit",
    "haiku": "flash",
    "sonnet": "pro",
    "opus": "pro",
}


@dataclass(slots=True)
class AntigravityWorkspaceOverlay:
    """1 runtime session 専用の workspace plugin overlay。"""

    cwd: str
    translated: TranslatedRuntimeConfig
    native_plugin_paths: tuple[str, ...] = ()
    plugin_root: Path | None = None
    _prepared: bool = False
    _owned_paths: list[Path] = field(default_factory=list)
    _leased_workspace: Path | None = None

    def prepare(self) -> None:
        """必要な customization がある場合だけ一時 plugin を生成する。"""
        if self._prepared:
            return

        workspace = Path(self.cwd).resolve()
        _claim_workspace(workspace)
        self._leased_workspace = workspace

        if not (
            self.translated.mcp_servers
            or self.translated.skills
            or self.translated.agents
            or self.native_plugin_paths
        ):
            self._prepared = True
            return

        parent = workspace / _PLUGIN_PARENT
        parent.mkdir(parents=True, exist_ok=True)
        _ensure_git_exclude(workspace)

        plugin_name = f"{_PLUGIN_PREFIX}{uuid.uuid4().hex[:12]}"
        plugin_root = parent / plugin_name
        plugin_root.mkdir(mode=0o700)
        self.plugin_root = plugin_root
        self._owned_paths.append(plugin_root)
        # Mark ownership before any subsequent write so cleanup can safely remove a
        # partially prepared overlay if manifest/MCP/skill staging fails.
        self._write_marker(plugin_root)

        self._write_json(
            plugin_root / "plugin.json",
            {
                "$schema": "https://antigravity.google/schemas/v1/plugin.json",
                "name": _safe_name(plugin_name.lstrip(".")),
                "description": "Ephemeral customization generated by Kotoyose",
            },
        )

        if self.translated.mcp_servers:
            self._write_json(
                plugin_root / "mcp_config.json",
                {
                    "mcpServers": {
                        _safe_name(name): _translate_mcp_server(server)
                        for name, server in self.translated.mcp_servers.items()
                    }
                },
            )

        self._stage_skills(plugin_root)
        self._stage_agents(plugin_root)
        self._stage_native_plugins(parent)

        self._prepared = True
        log.info(
            "antigravity.workspace_overlay.prepared",
            cwd=str(workspace),
            mcp_servers=list(self.translated.mcp_servers),
            skills=[skill.name for skill in self.translated.skills],
            agents=list(self.translated.agents),
            native_plugins=list(self.native_plugin_paths),
        )

    def cleanup(self) -> None:
        """Kotoyose が生成した customization だけを安全に取り除く。"""
        failed: list[Path] = []
        for owned in reversed(self._owned_paths):
            if (owned / _MARKER).exists():
                try:
                    shutil.rmtree(owned)
                except OSError as exc:
                    failed.append(owned)
                    log.error(
                        "antigravity.workspace_overlay.cleanup_failed",
                        path=str(owned),
                        error=str(exc),
                    )
            elif owned.exists():
                # 所有 marker が失われた path は削除しない。同じ workspace の lease
                # も保持し、残存 credential を別 session へ公開しない。
                failed.append(owned)

        if failed:
            self._owned_paths = list(reversed(failed))
            raise RuntimeError(
                "Antigravity resource overlay を安全に削除できませんでした。"
                " workspace の再利用を停止します"
            )

        self.plugin_root = None
        self._owned_paths.clear()
        self._prepared = False
        if self._leased_workspace is not None:
            _release_workspace(self._leased_workspace)
            self._leased_workspace = None

    def _stage_skills(self, plugin_root: Path) -> None:
        for skill in self.translated.skills:
            source = Path(skill.path).resolve().parent
            target = plugin_root / "skills" / _safe_name(skill.name)
            if target.exists():
                shutil.rmtree(target)
            shutil.copytree(source, target)

    def _stage_agents(self, plugin_root: Path) -> None:
        for name, agent in self.translated.agents.items():
            target = plugin_root / "agents" / _safe_name(name) / "agent.md"
            target.parent.mkdir(parents=True, exist_ok=True)

            tools: list[str] = []
            dropped_tools: list[str] = []
            for tool in agent.tools or []:
                mapped = _TOOL_MAP.get(tool)
                if mapped:
                    tools.append(mapped)
                else:
                    dropped_tools.append(tool)
            if dropped_tools:
                log.warning(
                    "antigravity.agent_tools_unmapped",
                    agent=name,
                    tools=dropped_tools,
                )

            frontmatter: dict[str, Any] = {
                "name": _safe_name(name),
                "description": agent.description,
                "mainAgent": False,
                "subagent": True,
                "model": _MODEL_MAP.get(agent.model, "inherit"),
            }
            if tools:
                frontmatter["tools"] = tools

            rendered = (
                "---\n"
                + yaml.safe_dump(
                    frontmatter,
                    allow_unicode=True,
                    sort_keys=False,
                    default_flow_style=False,
                )
                + "---\n\n# System Prompt\n\n"
                + agent.prompt.rstrip()
                + "\n"
            )
            target.write_text(rendered, encoding="utf-8")

    def _stage_native_plugins(self, parent: Path) -> None:
        """provider-specific Antigravity native plugins を workspace へコピーする。"""
        for index, raw_path in enumerate(self.native_plugin_paths):
            source = Path(raw_path).expanduser().resolve()
            manifest = source / "plugin.json"
            if not source.is_dir() or not manifest.is_file():
                raise ValueError(
                    f"antigravity.plugin_paths[{index}] は plugin.json を含む directory が必要です: {raw_path}"
                )
            target = parent / (
                f"{_PLUGIN_PREFIX}native-{index}-{_safe_name(source.name)}-{uuid.uuid4().hex[:6]}"
            )
            target.mkdir(mode=0o700)
            self._owned_paths.append(target)
            self._write_marker(target)
            shutil.copytree(source, target, dirs_exist_ok=True)

    @staticmethod
    def _write_marker(root: Path) -> None:
        AntigravityWorkspaceOverlay._write_json(
            root / _MARKER,
            {"generator": "kotoyose", "ephemeral": True},
        )

    @staticmethod
    def _write_json(path: Path, payload: dict[str, Any]) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        # mcp_config.json may contain Authorization headers. Keep generated files
        # private even when the workspace has a permissive umask.
        try:
            path.chmod(0o600)
        except OSError:
            pass


def _translate_mcp_server(server: dict[str, Any]) -> dict[str, Any]:
    """Kotoyose MCP definition を Antigravity の sparse MCP schema へ変換する。"""
    source = dict(server)
    source.pop("type", None)

    result: dict[str, Any] = {}
    command = source.pop("command", None)
    if isinstance(command, str) and command:
        result["command"] = command
        for key in ("args", "env", "cwd"):
            value = source.pop(key, None)
            if value is not None:
                result[key] = value
    else:
        url = (
            source.pop("serverUrl", None)
            or source.pop("url", None)
            or source.pop("httpUrl", None)
        )
        if not isinstance(url, str) or not url:
            raise ValueError(
                "Antigravity MCP server requires command (stdio) or URL (remote)"
            )
        # Antigravity CLI intentionally rejects the `url` / `httpUrl` keys.
        result["serverUrl"] = url

    # CLI の sparse schema に存在すると公式に明記されたキーだけを出力する。
    # SDK-only の enabled_tools / timeout_seconds を unknown field として書くと、
    # CLI の schema 更新次第で起動不能になり得るため silent passthrough はしない。
    sdk_only = {
        key: source.pop(key)
        for key in ("enabled_tools", "timeout_seconds")
        if key in source
    }
    if sdk_only:
        log.warning(
            "antigravity.mcp_cli_fields_unsupported",
            fields=sorted(sdk_only),
        )

    rename = {
        "auth_provider_type": "authProviderType",
        "disabled_tools": "disabledTools",
    }
    allowed = {"headers", "oauth", "disabled", "authProviderType", "disabledTools"}
    for key, value in source.items():
        if value is None:
            continue
        target = rename.get(key, key)
        if target not in allowed:
            log.warning("antigravity.mcp_cli_field_dropped", field=key)
            continue
        result[target] = value

    return result


def _safe_name(value: str) -> str:
    normalized = _SAFE_NAME.sub("-", value).strip("-_")
    return normalized or "resource"


def _claim_workspace(workspace: Path) -> None:
    """resource overlay を同じ workspace の 1 session だけに貸し出す。"""
    with _LEASE_LOCK:
        if workspace in _LEASED_WORKSPACES:
            raise RuntimeError(
                "Antigravity resource overlay は同じ cwd で同時利用できません。"
                " session ごとに別 worktree を指定してください"
            )
        _LEASED_WORKSPACES.add(workspace)


def _release_workspace(workspace: Path) -> None:
    """resource overlay の workspace lease を解放する。"""
    with _LEASE_LOCK:
        _LEASED_WORKSPACES.discard(workspace)


def _ensure_git_exclude(workspace: Path) -> None:
    """generated overlay を git status から隠す。

    ルール自体は worktree-local の info/exclude に残す。session ごとに元内容へ
    restore すると並列 session が互いの exclude を巻き戻す race が起きるため、
    idempotent な 1 行を永続させる方が安全。
    """
    exclude = _git_exclude_path(workspace)
    if exclude is None:
        return
    try:
        original = exclude.read_text(encoding="utf-8") if exclude.exists() else ""
        if _GIT_EXCLUDE_RULE in original.splitlines():
            return
        exclude.parent.mkdir(parents=True, exist_ok=True)
        prefix = "" if not original or original.endswith("\n") else "\n"
        exclude.write_text(
            original + prefix + _GIT_EXCLUDE_RULE + "\n",
            encoding="utf-8",
        )
    except OSError as exc:
        log.warning(
            "antigravity.workspace_overlay.git_exclude_failed",
            path=str(exclude),
            error=str(exc),
        )


def _git_exclude_path(workspace: Path) -> Path | None:
    dot_git = workspace / ".git"
    if dot_git.is_dir():
        return dot_git / "info" / "exclude"
    if not dot_git.is_file():
        return None
    try:
        text = dot_git.read_text(encoding="utf-8").strip()
    except OSError:
        return None
    prefix = "gitdir:"
    if not text.lower().startswith(prefix):
        return None
    git_dir = Path(text[len(prefix) :].strip())
    if not git_dir.is_absolute():
        git_dir = (workspace / git_dir).resolve()
    return git_dir / "info" / "exclude"
